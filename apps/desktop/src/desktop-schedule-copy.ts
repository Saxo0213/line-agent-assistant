export function scheduleTextFor(locale: Locale, key: ScheduleCopyKey, values?: Record<string, unknown>): string {
  const catalogs: Record<Locale, ScheduleCopy> = { en: ENGLISH_SCHEDULE_COPY, 'zh-TW': TRADITIONAL_CHINESE_SCHEDULE_COPY, ja: JAPANESE_SCHEDULE_COPY, ko: KOREAN_SCHEDULE_COPY };
  const template = (catalogs[locale] ?? ENGLISH_SCHEDULE_COPY)[key];
  return template.replace(/\{(arg\d+)\}/g, (slot, name: string) => {
    const value = values?.[name];
    return typeof value === 'number' ? new Intl.NumberFormat(locale).format(value) : String(value ?? slot);
  });
}

export function projectFoldersTextFor(locale: Locale, key: ProjectFoldersCopyKey, values?: Record<string, unknown>): string {
  const catalogs: Record<Locale, ProjectFoldersCopy> = { en: ENGLISH_PROJECT_FOLDERS_COPY, 'zh-TW': TRADITIONAL_CHINESE_PROJECT_FOLDERS_COPY, ja: JAPANESE_PROJECT_FOLDERS_COPY, ko: KOREAN_PROJECT_FOLDERS_COPY };
  const template = (catalogs[locale] ?? ENGLISH_PROJECT_FOLDERS_COPY)[key];
  return template.replace(/\{(arg\d+)\}/g, (slot, name: string) => String(values?.[name] ?? slot));
}

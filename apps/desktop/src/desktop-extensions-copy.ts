export function extensionsTextFor(locale: Locale, key: ExtensionsCopyKey, values?: Record<string, unknown>): string {
  const catalogs: Record<Locale, ExtensionsCopy> = { en: ENGLISH_EXTENSIONS_COPY, 'zh-TW': TRADITIONAL_CHINESE_EXTENSIONS_COPY, ja: JAPANESE_EXTENSIONS_COPY, ko: KOREAN_EXTENSIONS_COPY };
  const template = (catalogs[locale] ?? ENGLISH_EXTENSIONS_COPY)[key];
  return template.replace(/\{(arg\d+)\}/g, (slot, name: string) => String(values?.[name] ?? slot));
}

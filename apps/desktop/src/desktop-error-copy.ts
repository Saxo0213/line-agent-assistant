export function desktopErrorText(locale: import('./locale.js').Locale, code: unknown): string | undefined {
  if (typeof code !== 'string' || !Object.hasOwn(DESKTOP_ERROR_COPY, code)) return undefined;
  const copy = DESKTOP_ERROR_COPY[code as keyof typeof DESKTOP_ERROR_COPY];
  if (locale === 'zh-TW') return copy['zh-TW'];
  if (locale === 'ja') return JAPANESE_DESKTOP_ERROR_COPY[code as DesktopErrorCode];
  if (locale === 'ko') return KOREAN_DESKTOP_ERROR_COPY[code as DesktopErrorCode];
  return copy.en;
}

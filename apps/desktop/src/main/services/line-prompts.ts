/**
 * The `/help` reply. `/help` works only for the Primary Administrator in the one-to-one chat, so the list shows every command
 * and marks the ones that work only in a group/room or only in the one-to-one chat.
 */
export function lineHelpText(locale: Locale | string): string {
  const p = (key: LinePromptKey) => linePrompt(locale, key);
  const blocks: LinePromptKey[][] = [
    ['helpTitle', 'helpMentionNote'],
    ['helpSectionChat', 'helpCmdNew', 'helpCmdStop', 'helpCmdStatus', 'helpCmdQuota', 'helpCmdAgentOnce', 'helpCmdHelp'],
    ['helpSectionAgent', 'helpCmdAgentSwitch', 'helpCmdModel'],
    ['helpSectionGroup', 'helpCmdFree', 'helpCmdPersona', 'helpCmdRules'],
    ['helpSectionFolder', 'helpCmdFolder'],
    ['helpSectionUsers', 'helpCmdAdduser', 'helpCmdPermissions'],
  ];
  return blocks.map((block) => block.map(p).join('\n')).join('\n\n');
}

export function linePrompt(locale: Locale | string, key: LinePromptKey, params: PromptParams = {}): string {
  const parsed = LocaleSchema.safeParse(locale);
  return LINE_PROMPT_CATALOG[parsed.success ? parsed.data : 'en'][key](params);
}

export function linePrompt(locale: Locale | string, key: LinePromptKey, params: PromptParams = {}): string {
  const parsed = LocaleSchema.safeParse(locale);
  return LINE_PROMPT_CATALOG[parsed.success ? parsed.data : 'en'][key](params);
}
